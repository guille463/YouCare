CREATE TABLE mensaje (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id       BIGINT        NOT NULL,
    emisor_id     BIGINT        NOT NULL,
    contenido     VARCHAR(2000) NOT NULL,
    fecha_envio   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_lectura TIMESTAMPTZ,

    CONSTRAINT fk_mensaje_chat   FOREIGN KEY (chat_id)   REFERENCES chat (id)    ON DELETE CASCADE,
    CONSTRAINT fk_mensaje_emisor FOREIGN KEY (emisor_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT ck_mensaje_contenido CHECK (length(trim(contenido)) > 0),
    CONSTRAINT ck_mensaje_fecha_lectura CHECK (fecha_lectura IS NULL OR fecha_lectura >= fecha_envio)
);

-- Cargar los mensajes de un chat ya ordenados
CREATE INDEX idx_mensaje_chat_fecha ON mensaje (chat_id, fecha_envio);
CREATE INDEX idx_mensaje_emisor ON mensaje (emisor_id);