CREATE TABLE persona_cuidada (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT        NOT NULL,
    nombre           VARCHAR(100)  NOT NULL,
    apellidos        VARCHAR(150)  NOT NULL,
    fecha_nacimiento DATE          NOT NULL,
    direccion        VARCHAR(200)  NOT NULL,
    ciudad           VARCHAR(100)  NOT NULL,
    necesidades      VARCHAR(1000),

    CONSTRAINT fk_persona_cuidada_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id) ON DELETE CASCADE
);

CREATE INDEX idx_persona_cuidada_cliente ON persona_cuidada (cliente_id);