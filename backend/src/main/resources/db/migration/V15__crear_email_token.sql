CREATE TABLE email_token (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT      NOT NULL,
    hash_token       VARCHAR(64) NOT NULL,
    tipo             VARCHAR(20) NOT NULL,
    fecha_creacion   TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    fecha_uso        TIMESTAMPTZ,

    CONSTRAINT fk_email_token_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT uk_email_token_hash UNIQUE (hash_token),
    CONSTRAINT ck_email_token_hash CHECK (hash_token ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_email_token_tipo CHECK (tipo IN ('VERIFICACION', 'RECUPERACION')),
    CONSTRAINT ck_email_token_fechas CHECK (fecha_expiracion > fecha_creacion)
);

-- Invalidar los tokens anteriores del mismo tipo al pedir uno nuevo
CREATE INDEX idx_email_token_usuario_tipo ON email_token (usuario_id, tipo);