CREATE TABLE chat (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           BIGINT      NOT NULL,
    cuidador_id          BIGINT,
    empresa_id           BIGINT,
    fecha_creacion       TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_ultimo_mensaje TIMESTAMPTZ,

    CONSTRAINT fk_chat_cliente  FOREIGN KEY (cliente_id)  REFERENCES cliente (id)  ON DELETE CASCADE,
    CONSTRAINT fk_chat_cuidador FOREIGN KEY (cuidador_id) REFERENCES cuidador (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_empresa  FOREIGN KEY (empresa_id)  REFERENCES empresa (id)  ON DELETE CASCADE,
    -- Exactamente un proveedor: cuidador autónomo o empresa
    CONSTRAINT ck_chat_un_proveedor CHECK (num_nonnulls(cuidador_id, empresa_id) = 1),
    -- Un solo chat por pareja. Los NULL cuentan como distintos, así que cada UNIQUE solo actúa si su columna está rellena
    CONSTRAINT uk_chat_cliente_cuidador UNIQUE (cliente_id, cuidador_id),
    CONSTRAINT uk_chat_cliente_empresa  UNIQUE (cliente_id, empresa_id)
);

-- Los chats del cliente ya quedan indexados por los UNIQUE (empiezan por cliente_id)
CREATE INDEX idx_chat_cuidador ON chat (cuidador_id);
CREATE INDEX idx_chat_empresa  ON chat (empresa_id);
CREATE INDEX idx_chat_fecha_ultimo_mensaje ON chat (fecha_ultimo_mensaje);